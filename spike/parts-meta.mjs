#!/usr/bin/env node
// Generates spike/parts-meta.yml from spike/parts-list.txt: for each curated
// part, its library description, measured bounds and size in LDraw units, and
// the hand-written note about its origin and how it attaches. Bounds come from
// the geometry so they cannot drift; the notes are the part that needs a human.
//
// parts-list.txt: one part per line, "number<TAB>group<TAB>note". Blank lines
// and lines starting with # are skipped.
//
// usage: node spike/parts-meta.mjs

import fs from 'node:fs';
import path from 'node:path';
import { ROOT, partDescription, partGeometry, bounds, missing } from './ldraw.mjs';

const LIST = path.join(ROOT, 'spike/parts-list.txt');
const OUT = path.join(ROOT, 'spike/parts-meta.yml');
const r1 = (v) => Math.round(v * 10) / 10;
const q = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

const out = [
  '# Generated by spike/parts-meta.mjs from spike/parts-list.txt. Do not edit by hand:',
  '# change the list (the note column) and rerun.',
  '#',
  '# Units are LDraw units: 20 per stud, 24 per brick height, 8 per plate. +Y is down,',
  '# so a part whose body is "below" its origin has positive y in bounds. The front of a',
  '# part is -Z. bounds are [min, max] per axis in the part\'s own frame; size is the extent.',
  '',
];
let count = 0;
for (const raw of fs.readFileSync(LIST, 'utf8').split(/\r?\n/)) {
  const line = raw.trim();
  if (!line || line.startsWith('#')) continue;
  const [number, group = '', note = ''] = line.split('\t').map((s) => s.trim());
  const file = number.toLowerCase().endsWith('.dat') ? number.toLowerCase() : number.toLowerCase() + '.dat';
  const desc = partDescription(file);
  if (!desc) { console.warn(`not in library: ${number}`); continue; }
  const b = bounds(partGeometry(file).T);
  if (!b) { console.warn(`no geometry: ${number}`); continue; }
  const size = b.max.map((v, i) => r1(v - b.min[i]));
  out.push(`${number.replace(/\.dat$/i, '')}:`);
  out.push(`  name: ${q(desc)}`);
  if (group) out.push(`  group: ${group}`);
  out.push(`  bounds: { x: [${r1(b.min[0])}, ${r1(b.max[0])}], y: [${r1(b.min[1])}, ${r1(b.max[1])}], z: [${r1(b.min[2])}, ${r1(b.max[2])}] }`);
  out.push(`  size: { w: ${size[0]}, h: ${size[1]}, d: ${size[2]} }`);
  if (note) out.push(`  note: ${q(note)}`);
  out.push('');
  count++;
}
if (missing.size) console.warn('missing sub-parts:', [...missing].join(' '));
fs.writeFileSync(OUT, out.join('\n'));
console.log(`wrote ${OUT}: ${count} parts`);
